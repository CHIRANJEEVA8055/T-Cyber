/**
 * What the case window and its overview show: where the case stands, read from its records by rules.
 * Every sentence here is composed from stored facts; nothing is generated by a model.
 */

const NUM = ["no", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"];
const numWord = (n: number) => NUM[n] ?? String(n);
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
/** Lower-cases the first letter unless it starts an acronym ("KYC", "UPI"). */
const lcFirst = (s: string) => (/^[A-Z](?![A-Z0-9])/.test(s) ? s.charAt(0).toLowerCase() + s.slice(1) : s);
/** "07 Nov", "08 Nov" → "07 and 08 Nov"; different months keep their names. */
const dayList = (dates: Date[]) => {
  const ds = [...new Map(dates.sort((a, b) => a.getTime() - b.getTime()).map((d) => [formatDayMonthIST(d), d])).keys()];
  const months = new Set(ds.map((d) => d.slice(3)));
  return months.size === 1 && ds.length > 1 ? `${list(ds.map((d) => d.slice(0, 2)))} ${ds[0]!.slice(3)}` : list(ds);
};
const list = (xs: string[]) => (xs.length <= 1 ? (xs[0] ?? "") : `${xs.slice(0, -1).join(", ")} and ${xs.at(-1)}`);
const pct = (part: bigint, whole: bigint) => (whole > 0n ? Math.max(0, Math.min(100, Number((part * 1000n) / whole) / 10)) : 0);

/** Plain meanings of the sections officers use most. Sections not listed here are shown without a meaning. */
const SECTION_MEANING: Record<string, string> = {
  "BNS 318(4)": "cheating",
  "BNS 318": "cheating",
  "BNS 319(2)": "cheating by personation",
  "BNS 316(2)": "criminal breach of trust",
  "BNS 61(2)": "criminal conspiracy",
  "BNS 308": "extortion",
  "IT Act 66C": "identity theft",
  "IT Act 66D": "cheating by personation online",
};

/** The meaning key of a stated section: "BNS 318(4)", "IT Act 66D" (dashes dropped: "66-D" is 66D). */
function meaningKey(s: StatedSection): string {
  const act = /^i\.?\s*t\.?(\s+act)?$|^information technology act$/i.test(s.act.trim()) ? "IT Act" : s.act.trim().toUpperCase();
  return `${act} ${s.section.split(/\s+r\/w\s+/i)[0]!.replace(/-/g, "").toUpperCase()}`;
}

const IO_ROLE = "INVESTIGATING_OFFICER";

/** The case window's frame: title bar, station line, the side panel's counts and who is looking. */
export async function getCaseWindow(db: Db, user: SessionUser, caseId: string, at = now()) {
  const c = await loadCaseForUser(db, user, caseId, "read");
  const io = c.assignments.find((a) => a.role === IO_ROLE);
  const [ioUser, openCases, next] = await Promise.all([
    io ? db.user.findUnique({ where: { id: io.userId } }) : null,
    db.case.count({ where: { stationId: c.stationId, referenceType: "FIR", status: "OPEN" } }),
    getNextActions(db, user, caseId),
  ]);
  const ref = c.referenceType === "FIR" && c.firNumber ? `FIR ${c.firNumber}/${c.firYear}` : `Complaint ${c.complaintRef ?? c.id.slice(-6)}`;
  const initials = (user.rank === "Sub-Inspector" ? "S" : user.rank.charAt(0)) + user.displayName.replace(/^[A-Z]\.\s*/, "").charAt(0);
  const assigned = c.assignments.find((a) => a.userId === user.id);
  return {
    id: c.id,
    ref,
    title: c.title,
    stationName: c.station.name,
    day: Math.max(0, calendarDays(c.registeredAt ?? c.createdAt, at)),
    closed: c.status === "CLOSED",
    isDemo: c.isDemo,
    openCases,
    actionCount: next.counts.open,
    io: ioUser ? `${shortRank(ioUser.rank)} ${ioUser.displayName}` : null,
    viewer: {
      name: `${shortRank(user.rank)} ${user.displayName}`,
      initials: initials.toUpperCase(),
      role: assigned?.role === IO_ROLE ? "Investigating officer" : user.role === "SUPERVISOR" ? "Station supervisor" : assigned ? "Assisting officer" : "Officer",
    },
    canWrite: canWriteCase(user, { stationId: c.stationId, assignedUserIds: c.assignments.map((a) => a.userId) }),
  };
}
export type CaseWindowData = Awaited<ReturnType<typeof getCaseWindow>>;

type Finding = { findingType: string; classification: string; decision: string; summary: string; payloadJson: string; editedPayloadJson: string | null };
const payloadOf = (f: Finding) => JSON.parse(f.editedPayloadJson ?? f.payloadJson) as Record<string, unknown>;
const used = (f: Finding) => f.decision === "ACCEPTED" || f.decision === "EDITED";

export async function getCaseHome(db: Db, user: SessionUser, caseId: string, at = now()) {
  const c = await loadCaseForUser(db, user, caseId, "read");
  const writer = canWriteCase(user, { stationId: c.stationId, assignedUserIds: c.assignments.map((a) => a.userId) });
  const [claims, holds, allocations, refunds, transactions, requests, responses, entities, observations, assertions, rels, evidence, contacts, marker, users, next, complaint] = await Promise.all([
    db.victimClaim.findMany({ where: { caseId }, include: { victim: true }, orderBy: { createdAt: "asc" } }),
    db.hold.findMany({ where: { caseId }, include: { account: true } }),
    db.allocation.findMany({ where: { caseId } }),
    db.refund.findMany({ where: { caseId } }),
    db.transaction.findMany({ where: { caseId }, include: { toEntity: true, claim: { include: { victim: true } } } }),
    db.request.findMany({ where: { caseId, status: { not: "DISCARDED" } }, include: { recipient: true, items: true, subjects: { include: { entity: true } } } }),
    db.response.findMany({ where: { caseId, reviewStatus: "APPLIED" }, include: { findings: true, request: { include: { recipient: true, items: true } }, attachments: { select: { id: true, category: true } } }, orderBy: { appliedAt: "desc" } }),
    db.entity.findMany({ where: { caseId } }),
    db.locationObservation.findMany({ where: { caseId }, orderBy: { eventAt: "desc" } }),
    db.sourceAssertion.findMany({ where: { caseId, stance: "CONTRADICTS" }, include: { evidence: { select: { response: { select: { request: { select: { recipient: { select: { organisation: true } } } } } } } } } }),
    db.relationship.findMany({ where: { caseId, status: "DISPUTED" } }),
    db.evidenceItem.findMany({ where: { caseId, derivation: { in: ["ORIGINAL", "PREPARED"] } }, orderBy: { receivedAt: "asc" }, include: { derived: { select: { derivation: true } } } }),
    db.contactLog.findMany({ where: { caseId }, orderBy: { at: "asc" } }),
    db.reviewMarker.findUnique({ where: { caseId_userId_scope: { caseId, userId: user.id, scope: "OVERVIEW" } } }),
    db.user.findMany({ where: { stationId: c.stationId }, select: { id: true, displayName: true, rank: true, role: true, active: true } }),
    getNextActions(db, user, caseId),
    c.complaintRef ? db.complaint.findUnique({ where: { ackNumber: c.complaintRef } }) : null,
  ]);
  const entity = new Map(entities.map((e) => [e.id, e]));
  const label = (id: unknown) => (typeof id === "string" ? (entity.get(id)?.label ?? "an account") : "an account");
  const userName = (id: string | undefined) => {
    const u = users.find((x) => x.id === id);
    return u ? `${shortRank(u.rank)} ${u.displayName}` : null;
  };

  const ledger = computeLedger({
    claims: claims.map((x) => ({ id: x.id, lossMinor: x.lossAmountMinor, status: x.status })),
    holds: holds.map((h) => ({ id: h.id, status: h.status, confirmedMinor: h.confirmedAmountMinor })),
    allocations: allocations.map((a) => ({ id: a.id, holdId: a.holdId, claimId: a.claimId, amountMinor: a.amountMinor, status: a.status })),
    refunds: refunds.map((r) => ({ id: r.id, claimId: r.claimId, amountMinor: r.amountMinor, status: r.status })),
    transactions: transactions.map((t) => ({ id: t.id, layer: t.layer, amountMinor: t.amountMinor, claimId: t.claimId, kind: t.kind })),
  });
  const activeClaims = claims.filter((x) => x.status === "ACTIVE");
  const registered = c.registeredAt ?? c.createdAt;
  const day = Math.max(0, calendarDays(registered, at));
  const sections = sectionItems(c.legalSections);
  const stated = readSections(c.legalSections) ?? [];

  // --- Header ---------------------------------------------------------------------------------
  const sent = requests.filter((r) => !r.parentRequestId && !["DRAFT", "AWAITING_APPROVAL", "APPROVED", "SUBMISSION_FAILED"].includes(r.status));
  const answered = sent.filter((r) => r.status === "PARTIAL_RESPONSE" || r.status === "COMPLETE_RESPONSE");
  const substantive = responses.filter((r) => r.responseType !== "ACKNOWLEDGEMENT");
  const lastChange = responses[0]?.appliedAt ?? null;
  const returned = refunds.some((r) => r.status === "CREDIT_CONFIRMED" || r.status === "INITIATED" || r.status === "AUTHORISED") || allocations.some((a) => a.status === "CONFIRMED");
  const firstReply = substantive.find((r) => r.request?.recipient.organisationType === "BANK") ?? substantive.at(-1);
  const phase: { text: string; tone: Tone } =
    c.status === "CLOSED"
      ? { text: "Closed", tone: "neutral" }
      : returned
        ? { text: "Phase 3 · returning the money", tone: "ok" }
        : firstReply
          ? { text: `Phase 2 · first ${firstReply.request?.recipient.organisationType === "BANK" ? "bank " : ""}reply in`, tone: "info" }
          : sent.length
            ? { text: "Phase 1 · requests out", tone: "neutral" }
            : { text: "Phase 1 · just opened", tone: "neutral" };
  const lossMinor = ledger.totalLossMinor;
  const header = {
    breadcrumb: c.referenceType === "FIR" && c.firNumber ? `FIR ${c.firNumber}/${c.firYear}` : "Complaint",
    title: c.title,
    // The amount lost and how long the case has run; the registration date and sections are in the facts below.
    sub: activeClaims.length ? `${formatInr(lossMinor)} lost · day ${day}` : `Day ${day}`,
    phase,
    progress: sent.length ? `${answered.length} of ${sent.length} requests answered${lastChange ? ` · last change ${formatDayMonthIST(lastChange)}, ${formatDateTimeIST(lastChange, { label: false }).split(", ")[1]}` : ""}` : "No requests sent yet",
  };

  // --- Facts ----------------------------------------------------------------------------------
  const io = c.assignments.find((a) => a.role === IO_ROLE);
  const sup = c.assignments.find((a) => a.role === "SUPERVISOR") ?? null;
  const supervisor = sup ? userName(sup.userId) : (() => {
    const s = users.find((u) => u.role === "SUPERVISOR" && u.active);
    return s ? `${shortRank(s.rank)} ${s.displayName}` : null;
  })();
  const complainant = activeClaims[0]?.victim ?? null;
  const ownPhone = complainant ? entities.find((e) => e.kind === "PHONE" && /complainant'?s own number/i.test(e.caseRole ?? "")) : null;
  const lastTold = complainant ? contacts.filter((x) => x.victimEntityId === complainant.id).at(-1) : undefined;
  const channel = c.complaintChannel ?? complaint?.channel ?? null;
  const receivedAt = c.complaintReceivedAt ?? complaint?.receivedAt ?? null;
  const meanings = stated.map((s) => SECTION_MEANING[meaningKey(s)]).filter((x): x is string => !!x);
  const mo = caseMo(c);
  const facts = [
    { label: "NCRP acknowledgement", value: c.complaintRef ?? "Not recorded", mono: !!c.complaintRef, sub: receivedAt ? `Complaint ${formatDateIST(receivedAt)}${channel ? ` · ${channel === "HELPLINE_1930" ? "via the 1930 helpline" : "via the portal"}` : ""}` : "No NCRP complaint is linked", link: null },
    { label: "FIR registered", value: c.registeredAt ? formatDateTimeIST(c.registeredAt, { label: false }) : "Not registered", mono: true, sub: `${c.station.name}, ${getAppConfig().station.district} · day ${day} today`, link: null },
    { label: "Investigating officer", value: (io && userName(io.userId)) ?? "Not assigned", mono: false, sub: supervisor ? `Supervised by ${supervisor}` : "No supervisor assigned", link: null },
    (() => {
      // The station's investigation vertical (MO.docx) heads the tile; the case's own one-line MO sits under it.
      const how = mo.vertical ? `vertical ${moBasisText(mo)}${mo.reason && mo.basis !== "OFFICER" ? `: ${mo.reason}` : ""}` : "vertical not classified yet: set it with Edit details";
      const what = c.moSummary ?? (c.fraudCategory && c.fraudCategory !== c.title ? cap(c.fraudCategory.toLowerCase()) : c.title);
      return { label: "Modus operandi", value: mo.vertical ? `${mo.vertical.label}${mo.subtype ? ` · ${mo.subtype}` : ""}` : c.title, mono: false, sub: `${what} · ${how}`, link: null };
    })(),
    // Only the sections the FIR states (or an officer recorded); T-CYBER never proposes any.
    { label: "Sections", value: c.legalSections ? sections.join(" · ") : "Not stated", mono: false, sub: c.legalSections ? (meanings.length ? cap(meanings.join(" · ")) : "As recorded in the FIR") : "The FIR copy does not state them", link: null },
    {
      label: "Complainant",
      value: complainant ? `${complainant.label.replace(/\s*\(synthetic\)$/, "")}${ownPhone ? ` · ${shownId(ownPhone.value)}` : ""}` : "Not recorded",
      mono: false,
      sub: lastTold ? `Last told ${formatDayMonthIST(lastTold.at)} · ` : "Not contacted since the FIR · ",
      link: { text: "call log", href: `/cases/${caseId}/recovery#contacts` },
    },
  ];

  // --- Recovering the money -------------------------------------------------------------------
  const heldMinor = ledger.confirmedHeldMinor;
  const returnedMinor = ledger.confirmedRefundsMinor;
  const neitherMinor = ledger.neitherReturnedNorSecuredMinor ?? 0n;
  const heldAccounts = holds.filter((h) => h.status === "CONFIRMED_HELD" && (h.confirmedAmountMinor ?? 0n) > 0n).length;
  const cash = transactions.filter((t) => t.kind === "CASH_WITHDRAWAL").sort((a, b) => a.occurredAt.getTime() - b.occurredAt.getTime());
  const cashMinor = cash.reduce((s, t) => s + t.amountMinor, 0n);
  const moneyBits: string[] = [];
  if (cash.length) moneyBits.push(`${formatInr(cashMinor)} was withdrawn as cash${cash.length === 1 ? ` on ${formatDayMonthIST(cash[0]!.occurredAt)}` : ` in ${numWord(cash.length)} withdrawals`}${neitherMinor > 0n ? " and is being traced" : ""}.`);
  else if (neitherMinor > 0n) moneyBits.push(`${formatInr(neitherMinor)} is neither held nor returned yet.`);
  moneyBits.push(returnedMinor > 0n ? `${formatInr(returnedMinor)} has been returned to the victims.` : "Nothing has been returned to the victims yet.");
  const money = {
    heldMinor: heldMinor.toString(),
    held: formatInr(heldMinor),
    lost: formatInr(lossMinor),
    of: lossMinor > 0n ? (heldAccounts ? `of ${formatInr(lossMinor)} is held in ${numWord(heldAccounts)} ${heldAccounts === 1 ? "account" : "accounts"}` : `of ${formatInr(lossMinor)} is confirmed held`) : "No loss is recorded yet",
    bar: { held: pct(heldMinor, lossMinor), traced: pct(neitherMinor, lossMinor), returned: pct(returnedMinor, lossMinor) },
    sentence: lossMinor > 0n ? moneyBits.join(" ") : "Record each victim’s loss in the ledger to see what is held and what is still missing.",
    unknownHolds: holds.filter((h) => h.status !== "RELEASED" && h.confirmedAmountMinor === null).length,
  };
  money.bar = { ...money.bar, traced: Math.min(money.bar.traced, 100 - money.bar.held - money.bar.returned) };

  // --- Finding who did it ---------------------------------------------------------------------
  // Sightings place someone somewhere at a time: an ATM withdrawal, a cell site, a transaction's location.
  const SIGHTING = ["ATM_WITHDRAWAL", "TRANSACTION_LOCATION", "CELL_SITE"];
  const sightings = observations.filter((o) => SIGHTING.includes(o.observationType) && o.eventAt);
  // Accounts with a holder's name on some record (the FIR or a bank's KYC); a name is not proof of control.
  const namedAccounts = new Set(
    (await db.relationship.findMany({ where: { caseId, type: "REGISTERED_TO", status: { not: "REFUTED" } }, select: { fromEntityId: true } })).map((r) => r.fromEntityId).filter((id) => entity.get(id)?.kind === "BANK_ACCOUNT"),
  );
  const contradictionCount = new Set(assertions.map((a) => `${a.subjectType}:${a.subjectId}`)).size + rels.length + entities.filter((e) => e.verificationStatus === "DISPUTED").length;
  const leads = next.actions.filter((a) => !a.deferred && a.objective === "Identity").length;
  const suspects = entities.filter((e) => e.kind === "PERSON" && e.belongsTo === "SUSPECT" && e.verificationStatus === "CORROBORATED");
  const latest = sightings[0];
  const idBits: string[] = [];
  const named = namedAccounts.size;
  if (named) idBits.push(`${cap(numWord(named))} ${named === 1 ? "account has a named holder" : "accounts have named holders"}, but nothing yet shows who controlled ${named === 1 ? "it" : "them"}.`);
  if (latest) idBits.push(`The strongest lead is the ${latest.observationType === "CELL_SITE" ? "phone’s location" : latest.observationType === "ATM_WITHDRAWAL" ? "ATM withdrawal" : "transaction"} in ${latest.locationText.replace(/^(ATM|An ATM),?\s*/i, "").replace(/\s*\(synthetic\)$/, "")}.`);
  else if (next.actions.find((a) => a.objective === "Identity" && !a.deferred)) idBits.push(`Next: ${lcFirst(next.actions.find((a) => a.objective === "Identity" && !a.deferred)!.title)}.`);
  const identity = {
    headline: suspects.length ? `${cap(numWord(suspects.length))} ${suspects.length === 1 ? "person" : "people"} identified` : "No one identified yet",
    identified: suspects.length > 0,
    leads,
    sightings: sightings.length,
    sightingAge: latest?.eventAt ? Math.max(0, calendarDays(latest.eventAt, at)) : null,
    contradictions: contradictionCount,
    sentence: idBits.join(" ") || "No identifier has been traced to a person yet.",
  };

  // --- What changed since you last looked -----------------------------------------------------
  const since = marker?.reviewedAt ?? null;
  const fresh = responses.filter((r) => r.appliedAt && (!since || r.appliedAt > since) && r.responseType !== "ACKNOWLEDGEMENT");
  const changes: { at: Date; when: string; text: string }[] = [];
  const holdReplies = fresh.filter((r) => r.findings.some((f) => used(f) && f.findingType === "HOLD_STATUS" && BigInt(String(payloadOf(f).amountMinor ?? "0")) > 0n) && !r.findings.some((f) => used(f) && f.findingType === "TRANSACTION"));
  const byDay = new Map<string, typeof holdReplies>();
  for (const r of holdReplies) byDay.set(formatDateIST(r.appliedAt!), [...(byDay.get(formatDateIST(r.appliedAt!)) ?? []), r]);
  for (const group of byDay.values()) {
    const g = [...group].sort((a, b) => a.receivedAt.getTime() - b.receivedAt.getTime());
    const orgs = g.map((r) => shortOrg(r.request?.recipient.organisation ?? "A bank"));
    const amounts = g.map((r) => formatInr(BigInt(String(payloadOf(r.findings.find((f) => used(f) && f.findingType === "HOLD_STATUS")!).amountMinor))));
    const bits = [g.length === 1 ? `${orgs[0]} confirmed a hold of ${amounts[0]}.` : `${list(orgs)} confirmed holds: ${list(amounts)}.`];
    for (const r of g)
      for (const f of r.findings.filter((x) => used(x) && x.findingType === "CASH_WITHDRAWAL")) {
        const p = payloadOf(f);
        bits.push(`${formatInr(BigInt(String(p.amountMinor)))} had already been taken out of ${label(p.subjectEntityId)} in cash.`);
      }
    const latestAt = g.reduce((m, r) => (r.appliedAt! > m ? r.appliedAt! : m), g[0]!.appliedAt!);
    changes.push({ at: latestAt, when: formatDayMonthIST(latestAt), text: bits.join(" ") });
  }
  for (const r of fresh.filter((x) => !holdReplies.includes(x))) {
    const org = r.request?.recipient.organisation ?? "A provider";
    const f = r.findings.filter(used);
    const bits: string[] = [];
    const onward = f.filter((x) => x.findingType === "TRANSACTION" && x.classification === "NEW" && payloadOf(x).direction === "DEBIT");
    if (onward.length) {
      const legs = onward.map((x) => {
        const p = payloadOf(x);
        const cp = p.counterparty as { entityId?: string | null; value?: string | null } | undefined;
        return `${cp?.entityId ? label(cp.entityId) : cp?.value ? `account ${shownId(cp.value)}` : "an account"} (${formatInr(BigInt(String(p.amountMinor)))})`;
      });
      bits.push(`${shortOrg(org)}’s statement shows the money moved on to ${list(legs)}.`);
    }
    const phones = f.filter((x) => x.findingType === "RELATIONSHIP" && x.classification === "NEW").map((x) => payloadOf(x).from as { kind?: string; value?: string } | undefined).filter((x) => x?.kind === "PHONE");
    if (phones.length) bits.push(`${bits.length ? "It also gave" : `${shortOrg(org)} gave`} ${phones.length === 1 ? `a new mobile number, ${shownId(phones[0]!.value ?? "")}` : `${numWord(phones.length)} new mobile numbers`}.`);
    for (const x of f.filter((y) => y.findingType === "PRESERVATION_CONFIRMED")) {
      const p = payloadOf(x);
      const e = typeof p.entityId === "string" ? entity.get(p.entityId) : undefined;
      const what = e?.kind === "PLATFORM_PROFILE" ? `the “${e.value}” profile records` : e ? `the records for ${e.label}` : "the records";
      bits.push(`The ${lcFirst(org)} preserved ${what}${p.preservedUntil ? ` until ${formatDateIST(new Date(String(p.preservedUntil)))}` : ""}.`);
      const disclosure = e && requests.some((q) => q.category === "INFORMATION" && q.subjects.some((s) => s.entityId === e.id));
      if (e && !disclosure) bits.push("The request to disclose them is not written yet.");
    }
    const missing = f.filter((x) => x.findingType === "ITEM_NOT_PROVIDED").map((x) => r.request?.items.find((i) => i.id === payloadOf(x).requestItemId)?.label ?? "an item");
    if (missing.length) bits.push(`The ${list(missing.map((m) => (/^[A-Z]{2,}/.test(m) ? m.split(" ")[0]! : lcFirst(m))))} you asked for ${missing.length === 1 ? "was" : "were"} not included.`);
    if (!bits.length) bits.push(`${shortOrg(org)} replied${r.request ? ` to ${r.request.reference}` : ""}: ${lcFirst(f[0]?.summary ?? r.subject)}.`);
    changes.push({ at: r.appliedAt!, when: formatDayMonthIST(r.appliedAt!), text: bits.join(" ") });
  }
  changes.sort((a, b) => b.at.getTime() - a.at.getTime());

  // --- Waiting on -----------------------------------------------------------------------------
  const waiting: { text: string; pill: { text: string; tone: Tone }; href: string }[] = [];
  const unread = writer ? await db.inboxMessage.findMany({ where: { status: "UNREAD" } }) : [];
  const inboxFor = new Map<string, "REPLY" | "ACK">();
  for (const m of unread) {
    const best = (await rankRequestsFor(db, caseId, m))[0];
    if (!best || best.score < 70) continue;
    const kind = /acknowledg|received your|under process/i.test(`${m.subject} ${m.bodyText}`) ? "ACK" : "REPLY";
    if (inboxFor.get(best.request.id) !== "REPLY") inboxFor.set(best.request.id, kind);
  }
  const reqWhat = (r: (typeof requests)[number]) => {
    const t = new Set(r.items.map((i) => i.itemType));
    const subj = r.subjects[0]?.entity;
    const on = subj ? (subj.kind === "PHONE" ? ` for ${shownId(subj.value)}` : subj.kind === "BANK_ACCOUNT" ? ` for ${shownId(subj.value)}` : subj.kind === "PLATFORM_PROFILE" ? ` for “${subj.value}”` : "") : "";
    if (r.recipient.organisationType === "NPCI") return "UPI trace";
    if (r.category === "HOLD") return `hold${on}`;
    if (r.category === "PRESERVATION") return `preservation${on}`;
    if (t.has("CDR")) return `CDR${on}`;
    if (t.has("STATEMENT")) return `statement${on}`;
    if (t.has("KYC")) return `KYC${on}`;
    return `records${on}`;
  };
  for (const r of sent.filter((x) => x.status === "SUBMITTED" || x.status === "ACKNOWLEDGED").sort((a, b) => (a.submittedAt?.getTime() ?? 0) - (b.submittedAt?.getTime() ?? 0))) {
    const days = calendarDays(r.submittedAt ?? r.createdAt, at);
    const inInbox = inboxFor.get(r.id);
    const acked = r.status === "ACKNOWLEDGED";
    waiting.push({
      text: `${shortOrg(r.recipient.organisation)} · ${reqWhat(r)}${!acked && !inInbox && days >= 3 ? ", no acknowledgement" : ""}`,
      pill: inInbox ? { text: inInbox === "ACK" ? "Acknowledged · in the inbox" : "Reply in the inbox", tone: "info" } : { text: `${days} ${days === 1 ? "day" : "days"}`, tone: !acked && days >= 3 ? "gap" : "neutral" },
      href: inInbox ? `/cases/${caseId}/requests?inbox=1` : `/cases/${caseId}/requests/${r.id}`,
    });
  }
  for (const r of requests.filter((x) => x.status === "PARTIAL_RESPONSE" && !x.parentRequestId)) {
    const missing = r.items.filter((i) => i.status === "PENDING" || i.status === "NOT_PROVIDED");
    if (!missing.length) continue;
    const reminder = requests.filter((x) => x.parentRequestId === r.id).at(-1);
    const what = list(missing.map((i) => (i.itemType === "KYC" ? "KYC" : lcFirst(i.label))));
    const reminderSent = reminder && !["DRAFT", "AWAITING_APPROVAL", "APPROVED", "SUBMISSION_FAILED"].includes(reminder.status);
    waiting.push({
      text: `${shortOrg(r.recipient.organisation)} · the missing ${what}`,
      pill: reminderSent ? { text: `Reminded ${calendarDays(reminder.submittedAt ?? reminder.createdAt, at)}d ago`, tone: "neutral" } : { text: "Remind", tone: "wait" },
      href: reminder && !reminderSent ? `/cases/${caseId}/actions` : `/cases/${caseId}/requests/${r.id}`,
    });
  }
  const lastByVictim = new Map<string, (typeof contacts)[number]>();
  for (const x of contacts) lastByVictim.set(x.victimEntityId, x);
  for (const x of lastByVictim.values()) {
    if (!x.followUp) continue;
    waiting.push({ text: `${entity.get(x.victimEntityId)?.label.replace(/\s*\(synthetic\)$/, "") ?? "Victim"} · ${lcFirst(x.followUp)}`, pill: { text: "Ask", tone: "neutral" }, href: `/cases/${caseId}/recovery#contacts` });
  }
  for (const h of holds.filter((x) => x.expiresAt && x.status !== "RELEASED")) {
    const d = calendarDays(at, h.expiresAt!);
    if (d < 0 || d > 7) continue;
    waiting.push({ text: `${h.account.label} · hold lapses ${d === 0 ? "today" : `on ${formatDayMonthIST(h.expiresAt!)}`}`, pill: { text: d === 0 ? "Today" : `${d} ${d === 1 ? "day" : "days"}`, tone: "gap" }, href: `/cases/${caseId}/recovery` });
  }

  // --- Open questions -------------------------------------------------------------------------
  const questions: { text: string; tone: "gap" | "neutral" }[] = [];
  if (next.actions.some((a) => a.ruleId === "FUNDS_ALLOCATION_BASIS")) {
    const firstLayer = new Map<string, number>();
    for (const t of transactions.filter((x) => x.kind === "VICTIM_PAYMENT")) firstLayer.set(t.toEntityId, (firstLayer.get(t.toEntityId) ?? 0) + 1);
    const shared = [...firstLayer.entries()].sort((a, b) => b[1] - a[1])[0];
    const big = holds.filter((h) => h.status === "CONFIRMED_HELD" && (h.confirmedAmountMinor ?? 0n) > 0n).sort((a, b) => Number((b.confirmedAmountMinor ?? 0n) - (a.confirmedAmountMinor ?? 0n)))[0];
    if (big) questions.push({ text: `Whose money is the ${formatInr(big.confirmedAmountMinor!)} in ${big.account.label}? ${shared && shared[1] > 1 ? `${activeClaims.length === 2 ? "Both victims" : "The victims"} paid into ${label(shared[0])} first.` : "More than one victim’s money reached it."}`, tone: "gap" });
  }
  const txById = new Map(transactions.map((t) => [t.id, t]));
  for (const a of assertions) {
    const t = a.subjectType === "TRANSACTION" ? txById.get(a.subjectId) : undefined;
    const who = t?.claim?.victim.label.replace(/\s*\(synthetic\)$/, "") ?? "a victim";
    const org = a.evidence.response?.request?.recipient.organisation;
    const dates = /dates this \w+ (.+?) here but (.+?) in the recorded payment/.exec(a.note ?? "");
    if (t && dates && org) questions.push({ text: `${shortOrg(org)} dates ${who}’s ${formatInr(t.amountMinor)} payment ${dates[1]!.replace(/ \d{4}$/, "")}; the FIR says ${dates[2]!.replace(/ \d{4}$/, "")}.`, tone: "gap" });
    else if (a.note) questions.push({ text: a.note.split(/(?<=\.)\s/)[0]!, tone: "gap" });
  }
  for (const r of rels) questions.push({ text: r.statement, tone: "gap" });
  for (const t of transactions.filter((x) => x.reference?.includes("?"))) {
    const n = (t.reference!.match(/\?/g) ?? []).length;
    questions.push({ text: `${cap(numWord(n))} ${n === 1 ? "character" : "characters"} of ${t.claim?.victim.label.replace(/\s*\(synthetic\)$/, "") ?? "a victim"}’s ${t.channel === "UPI" ? "UPI " : ""}reference ${n === 1 ? "is" : "are"} unreadable.`, tone: "neutral" });
  }

  // --- Case file ------------------------------------------------------------------------------
  const replyEvidence = new Set(responses.flatMap((r) => r.attachments.map((a) => a.id)));
  const messageIds = new Set(responses.map((r) => r.messageEvidenceId).filter(Boolean));
  const CAT: Record<string, { pill: string; order: number }> = { FIR_COPY: { pill: "FIR", order: 0 }, COMPLAINT: { pill: "Portal", order: 1 }, TRANSACTION_RECORD: { pill: "Evidence", order: 2 }, SCREENSHOT: { pill: "Evidence", order: 2 }, OTHER: { pill: "Evidence", order: 3 } };
  const files: { name: string; sub: string; pill: { text: string; tone: Tone } }[] = [];
  const own = evidence.filter((x) => !replyEvidence.has(x.id) && !messageIds.has(x.id) && !x.responseId && x.category !== "EMAIL_MESSAGE");
  for (const e of own.sort((a, b) => (CAT[a.category]?.order ?? 3) - (CAT[b.category]?.order ?? 3) || a.receivedAt.getTime() - b.receivedAt.getTime())) {
    const translated = e.derived.some((d) => d.derivation === "TRANSLATION");
    const named = e.category === "FIR_COPY" || e.title === e.fileName;
    const parts = [
      named ? (e.category === "FIR_COPY" ? (e.derivation === "PREPARED" ? "prepared from details entered by hand, not the CCTNS copy" : "FIR") : null) : e.fileName,
      e.pageCount ? `${e.pageCount} ${e.pageCount === 1 ? "page" : "pages"}` : null,
      translated ? "translated" : null,
      formatDayMonthIST(e.receivedAt),
      e.sha256 ? "hash recorded" : null,
    ].filter(Boolean);
    files.push({ name: named ? e.fileName : e.title, sub: parts.join(" · "), pill: { text: CAT[e.category]?.pill ?? "Evidence", tone: "neutral" } });
  }
  if (substantive.length) {
    const orgs = [...new Set([...substantive].sort((a, b) => Number(b.request?.recipient.organisationType === "BANK") - Number(a.request?.recipient.organisationType === "BANK") || (a.request?.recipient.organisation ?? "").localeCompare(b.request?.recipient.organisation ?? "")).map((r) => shortOrg(r.request?.recipient.organisation ?? "a provider")))];
    const attachments = substantive.reduce((s, r) => s + r.attachments.filter((a) => a.category !== "EMAIL_MESSAGE").length, 0);
    files.push({
      name: `Replies from ${list(orgs.map((o, i) => (i > 0 && /^[A-Z][a-z]/.test(o) && !/^Bank\b/.test(o) ? lcFirst(o) : o)))}`,
      sub: `${attachments ? `${attachments} ${attachments === 1 ? "attachment" : "attachments"}, ` : ""}${dayList(substantive.map((r) => r.receivedAt))} · kept with their hashes`,
      pill: { text: `${substantive.length} ${substantive.length === 1 ? "reply" : "replies"}`, tone: "ok" },
    });
  }

  return {
    caseId,
    header,
    canWrite: writer,
    actionsToReview: next.counts.open,
    facts,
    money,
    identity,
    doNext: next.actions.filter((a) => !a.deferred).slice(0, 4).map((a) => ({ rank: a.rank, title: a.title, status: a.status })),
    changes: { since: since?.toISOString() ?? null, sinceLabel: since ? `${formatDayMonthIST(since)}, ${formatDateTimeIST(since, { label: false }).split(", ")[1]}` : null, items: changes.slice(0, 6).map(({ when, text }) => ({ when, text })), more: Math.max(0, changes.length - 6) },
    waiting,
    questions,
    files,
  };
}
