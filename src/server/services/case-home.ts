/** "Mark as seen": later changes are listed as new on the overview. Read access is enough; it is per officer. */
export async function markOverviewSeen(db: Db, user: SessionUser, caseId: string) {
  return db.$transaction(async (tx) => {
    await loadCaseForUser(tx, user, caseId, "read");
    const at = now();
    await tx.reviewMarker.upsert({ where: { caseId_userId_scope: { caseId, userId: user.id, scope: "OVERVIEW" } }, create: { caseId, userId: user.id, scope: "OVERVIEW", reviewedAt: at }, update: { reviewedAt: at } });
    await recordAudit(tx, { caseId, actorId: user.id, action: "overview.seen", objectType: "Case", objectId: caseId, summary: "Overview marked as seen; later changes will be listed as new" });
    return at;
  });
}
