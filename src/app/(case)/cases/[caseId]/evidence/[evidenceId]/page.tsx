import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { ArrowLeft, Download, ExternalLink, ListChecks } from "lucide-react";
import { requireUser } from "@/server/auth/current-user";
import { getDb } from "@/server/db";
import { AppError } from "@/server/errors";
import { getEvidenceDetail } from "@/server/services/evidence-views";
import { PageBody, Panel, DefinitionList } from "@/components/app/page";
import { StatusBadge, Tag } from "@/components/app/status-badge";
import { DateTime } from "@/components/app/datetime";
import { Button } from "@/components/ui/button";
import { InlineAlert } from "@/components/ui/feedback";
import { DocumentViewer } from "@/features/evidence/components/document-viewer";
import { DERIVATION_LABELS, EVIDENCE_CATEGORY_LABELS } from "@/lib/labels";
import { cn } from "@/lib/cn";

export const metadata: Metadata = { title: "Evidence item" };

export default async function EvidenceItemPage({ params, searchParams }: { params: Promise<{ caseId: string; evidenceId: string }>; searchParams: Promise<{ page?: string; line?: string; row?: string; view?: string }> }) {
  const user = await requireUser();
  const { caseId, evidenceId } = await params;
  const sp = await searchParams;
  let e;
  try {
    e = await getEvidenceDetail(getDb(), user, evidenceId);
  } catch (err) {
    if (err instanceof AppError && err.code === "NOT_FOUND") notFound();
    throw err;
  }
  if (e.caseId !== caseId) notFound();
  const highlight = sp.page || sp.line || sp.row ? { page: sp.page ? Number(sp.page) : null, line: sp.line ? Number(sp.line) : null, row: sp.row ? Number(sp.row) : null } : null;
  const fileUrl = `/api/evidence/${e.id}/file`;
  const showOriginal = sp.view === "original";
  const embeddable = e.mimeType === "application/pdf" || e.mimeType.startsWith("image/");
  const derived = e.derivation !== "ORIGINAL";

  return (
    <PageBody>
      <Link href={`/cases/${caseId}/evidence`} className="inline-flex items-center gap-1.5 text-label font-medium text-action hover:underline">
        <ArrowLeft aria-hidden="true" className="size-4" />
        Back to evidence library
      </Link>
      <div className="mt-3 flex flex-col gap-3 border-b border-line pb-5 lg:flex-row lg:items-end lg:justify-between">
        <div className="min-w-0">
          <div className="flex flex-wrap items-center gap-2">
            <h2 className="text-title font-semibold tracking-tight text-ink">{e.title}</h2>
            <Tag tone={e.derivation === "AI_SUMMARY" ? "warning" : derived ? "info" : "neutral"}>{DERIVATION_LABELS[e.derivation]}</Tag>
            <Tag>{EVIDENCE_CATEGORY_LABELS[e.category] ?? e.category}</Tag>
            {e.isSynthetic ? <Tag>Synthetic</Tag> : null}
          </div>
          <p className="mt-1 text-body text-ink-2">
            {e.fileName}. {e.sourceDescription}
          </p>
          {e.parent ? (
            <p className="mt-1 text-label text-ink-2">
              Derived from{" "}
              <Link href={`/cases/${caseId}/evidence/${e.parent.id}`} className="font-medium text-action hover:underline">
                {e.parent.title}
              </Link>
            </p>
          ) : null}
        </div>
        <div className="flex flex-wrap gap-2">
          {e.pendingCandidates ? (
            <Button asChild variant="primary">
              <Link href={`/cases/${caseId}/evidence/${e.id}/review`}>
                <ListChecks aria-hidden="true" />
                Review {e.pendingCandidates} extracted {e.pendingCandidates === 1 ? "item" : "items"}
              </Link>
            </Button>
          ) : e.lastRun?.status === "COMPLETED" ? (
            <Button asChild variant="secondary">
              <Link href={`/cases/${caseId}/evidence/${e.id}/review`}>
                <ListChecks aria-hidden="true" />
                View extraction review
              </Link>
            </Button>
          ) : null}
          <Button asChild variant="secondary">
            <a href={`${fileUrl}?download=1`}>
              <Download aria-hidden="true" />
              Download original
            </a>
          </Button>
        </div>
      </div>

      {e.derivation === "AI_SUMMARY" ? (
        <InlineAlert tone="warning" className="mt-5" title="Demo assistant summary: not evidence">
          This text was generated by the assistant&apos;s rules as a navigation aid. Rely on the original it was derived from.
        </InlineAlert>
      ) : null}

      <div className="mt-6 grid grid-cols-1 gap-6 lg:grid-cols-12">
        <div className="min-w-0 lg:col-span-8">
          <Panel
            id="document"
            title={showOriginal ? "Original file" : "Extracted text"}
            description={showOriginal ? "Served from protected storage after an access check." : "Exactly as parsed, with the page, line and row numbers used in source references."}
            actions={
              <nav aria-label="Document view" className="flex gap-1 rounded-[var(--radius-control)] border border-line p-0.5">
                <Link href={`/cases/${caseId}/evidence/${e.id}`} aria-current={!showOriginal ? "page" : undefined} className={cn("rounded-[4px] px-2.5 py-1 text-label font-medium", !showOriginal ? "bg-action-tint text-action" : "text-ink-2 hover:text-ink")}>
                  Extracted text
                </Link>
                <Link href={`/cases/${caseId}/evidence/${e.id}?view=original`} aria-current={showOriginal ? "page" : undefined} className={cn("rounded-[4px] px-2.5 py-1 text-label font-medium", showOriginal ? "bg-action-tint text-action" : "text-ink-2 hover:text-ink")}>
                  Original file
                </Link>
              </nav>
            }
          >
            {showOriginal ? (
              embeddable ? (
                e.mimeType === "application/pdf" ? (
                  <iframe title={`Original: ${e.title}`} src={fileUrl} className="h-[75vh] w-full rounded-[var(--radius-control)] border border-line" />
                ) : (
                  // eslint-disable-next-line @next/next/no-img-element
                  <img src={fileUrl} alt={`Original image: ${e.title}`} className="max-w-full rounded-[var(--radius-control)] border border-line" />
                )
              ) : (
                <div className="flex flex-col items-start gap-3">
                  <p className="text-body text-ink-2">This file type is shown as text in the extracted view, or can be opened directly.</p>
                  <Button asChild variant="secondary" size="sm">
                    <a href={fileUrl} target="_blank" rel="noopener">
                      <ExternalLink aria-hidden="true" />
                      Open original in a new tab
                    </a>
                  </Button>
                </div>
              )
            ) : e.segments.length ? (
              <DocumentViewer segments={e.segments} highlight={highlight} />
            ) : (
              <InlineAlert tone="warning" title="No extracted text">
                {e.processingNote ?? "Nothing could be extracted from this file."} Open the original file to review it.
              </InlineAlert>
            )}
          </Panel>
        </div>

        <div className="flex min-w-0 flex-col gap-6 lg:col-span-4">
          <Panel id="integrity" title="Integrity" description="Computed from the stored original bytes">
            <DefinitionList
              columns={1}
              items={[
                { term: "SHA-256", value: <span className="break-all font-mono text-label">{e.sha256}</span> },
                { term: "Size and type", value: `${e.sizeBytes.toLocaleString("en-IN")} bytes, ${e.mimeType}${e.pageCount ? `, ${e.pageCount} page${e.pageCount === 1 ? "" : "s"}` : ""}` },
                { term: "Received", value: <DateTime iso={e.receivedAt} /> },
                { term: "Stored by", value: <>{e.uploadedBy}, <DateTime iso={e.uploadedAt} /></> },
                { term: "Processing", value: <StatusBadge kind="processing" value={e.processingStatus} /> },
              ]}
            />
            <p className="mt-3 text-meta text-ink-3">The hash records the file as received. It does not by itself certify the document; any certificate required by law must come from the producing institution.</p>
          </Panel>

          <Panel id="history" title="Processing History" bodyClassName="p-0">
            <ol className="divide-y divide-line">
              {e.events.map((ev) => (
                <li key={ev.id} className="px-5 py-2.5">
                  <p className="flex items-center gap-2 text-label font-medium text-ink">
                    <span className={cn("size-2 rounded-full", ev.outcome === "OK" ? "bg-success" : ev.outcome === "FAILED" ? "bg-danger" : "bg-[#c07a1c]")} aria-hidden="true" />
                    {ev.step.replace(/_/g, " ").toLowerCase().replace(/^\w/, (c) => c.toUpperCase())}
                    <span className="sr-only">: {ev.outcome}</span>
                  </p>
                  <p className="mt-0.5 break-words text-label text-ink-2">{ev.detail}</p>
                  <p className="text-meta text-ink-3">
                    <DateTime iso={ev.at} />
                    {ev.actor ? `, ${ev.actor}` : ""}
                  </p>
                </li>
              ))}
            </ol>
          </Panel>

          {e.derived.length ? (
            <Panel id="derived" title="Derived from This Document" bodyClassName="p-0">
              <ul className="divide-y divide-line">
                {e.derived.map((d) => (
                  <li key={d.id} className="flex items-center justify-between gap-3 px-5 py-2.5">
                    <Link href={`/cases/${caseId}/evidence/${d.id}`} className="text-body text-action hover:underline">
                      {d.title}
                    </Link>
                    <Tag tone={d.derivation === "AI_SUMMARY" ? "warning" : "neutral"}>{DERIVATION_LABELS[d.derivation]}</Tag>
                  </li>
                ))}
              </ul>
            </Panel>
          ) : null}

          <Panel id="citations" title="Facts Citing This Document" description={`${e.citations.length} source ${e.citations.length === 1 ? "reference" : "references"}`} bodyClassName="p-0">
            {e.citations.length ? (
              <ul className="max-h-96 divide-y divide-line overflow-y-auto">
                {e.citations.map((c) => (
                  <li key={c.id} className="px-5 py-2.5">
                    <p className="text-label text-ink">
                      {c.subject}
                      {c.stance === "CONTRADICTS" ? <span className="ml-1.5 font-medium text-danger">(contradicts)</span> : null}
                    </p>
                    <p className="text-meta text-ink-3">{c.locator}</p>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="px-5 py-4 text-body text-ink-2">No case facts cite this document yet.</p>
            )}
          </Panel>
        </div>
      </div>
    </PageBody>
  );
}
